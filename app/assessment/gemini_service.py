def explain_agricultural_assessment(
    context: GeminiAssessmentContext,
    client: GeminiModelClient | None = None,
    model: str | None = None,
) -> FarmerAgriculturalResponse:
    """Explains a deterministic agricultural assessment using Gemini 2.5 Flash with fallback (DEC-024).

    Flow:
    1. Builds prompt using build_gemini_prompt(context).
    2. Calls Gemini 2.5 Flash requesting structured JSON output conforming to FarmerAgriculturalResponse.
    3. Runs automated 3-stage validation on model output.
    4. If any failure or validation rejection occurs, returns deterministic fallback.

    Args:
        context: Authoritative GeminiAssessmentContext boundary envelope.
        client: Optional GeminiModelClient for dependency injection (defaults to DefaultGeminiClient).
        model: Optional model identifier (defaults to config.model / gemini-2.5-flash).

    Returns:
        FarmerAgriculturalResponse: Validated farmer-facing explanation payload.
    """
    if not isinstance(context, GeminiAssessmentContext):
        raise TypeError(
            f"context must be a GeminiAssessmentContext instance, got {type(context)!r}"
        )

    # Resolve client and model
    resolved_client = client if client is not None else DefaultGeminiClient()
    resolved_model = model if model is not None else config.model

    try:
        # Build authoritative prompt
        prompt_text = build_gemini_prompt(context)

        # Configure structured JSON output via Google GenAI SDK
        from google.genai import types

        generate_config = types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=FarmerAgriculturalResponse,
            temperature=0.2,
        )

        # Invoke model
        response_obj = resolved_client.generate_content(
            model=resolved_model,
            contents=prompt_text,
            config=generate_config,
        )

        # Parse text response
        raw_text = ""
        if hasattr(response_obj, "text") and response_obj.text:
            raw_text = response_obj.text
        elif isinstance(response_obj, str):
            raw_text = response_obj
        else:
            raw_text = str(response_obj)

        # Stage 1: Pydantic Schema Validation
        parsed_dict = json.loads(raw_text)
        validated_response = FarmerAgriculturalResponse.model_validate(parsed_dict)

        # Stage 2 & 3: Boundary & Epistemic Validation
        is_valid, reason = validate_response_payload(validated_response, context)
        if not is_valid:
            logger.warning("Gemini agricultural response failed boundary validation: %s", reason)
            return generate_deterministic_fallback_explanation(context)

        return validated_response

    except Exception as exc:
        logger.warning("Gemini explanation generation failed or raised error: %s", type(exc).__name__)
        return generate_deterministic_fallback_explanation(context)
