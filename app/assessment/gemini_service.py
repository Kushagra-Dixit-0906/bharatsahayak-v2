# ==============================================================================
# Multi-Layered Validation Logic
# ==============================================================================

def validate_response_payload(
    response: FarmerAgriculturalResponse,
    context: GeminiAssessmentContext,
) -> tuple[bool, str]:
    """Applies Stage 1-3 validations against a FarmerAgriculturalResponse.

    Returns:
        tuple[bool, str]: (is_valid, rejection_reason)
    """
    # 1. Structural / Basic Constraints
    if not response.headline.strip():
        return False, "Empty headline"
    if not response.summary.strip():
        return False, "Empty summary"
    if not response.interpretation.strip():
        return False, "Empty interpretation"

    # Normal Gemini response must not claim to be fallback
    if response.is_fallback:
        return False, "Non-fallback Gemini response had is_fallback=True"

    # 2. Epistemic Consistency Checks
    if (
        context.assessment_status == "insufficient_evidence"
        or context.overall_condition == "insufficient_evidence"
    ):
        # Must not claim thriving or favorable conditions when evidence is insufficient
        lower_summary = (response.headline + " " + response.summary).lower()
        if any(
            claim in lower_summary
            for claim in [
                "crop is thriving",
                "crop is completely healthy",
                "excellent crop health",
                "favorable growth condition",
                "फसल पूरी तरह स्वस्थ",
                "उत्कृष्ट स्थिति",
            ]
        ):
            return False, "Claimed favorable condition during insufficient evidence"

    # Must not invent numerical AI confidence or probabilities in interpretation
    if re.search(r"\b\d+%\s+confidence\b|\bconfidence\s+score\s*:\s*\d+", response.interpretation, re.IGNORECASE):
        return False, "Invented numerical confidence score in interpretation"

    # 3. Defense-in-Depth Banned Content Checks
    full_text = " ".join(
        [
            response.headline,
            response.summary,
            response.interpretation,
            *response.observations,
            *(step.description for step in response.recommended_next_steps),
            *response.limitations,
        ]
    )

    for pattern in BANNED_DOSAGE_PATTERNS:
        if pattern.search(full_text):
            return False, f"Banned quantitative dosage detected: {pattern.pattern}"

    for pattern in BANNED_CHEMICAL_PRESCRIPTIONS:
        if pattern.search(full_text):
            return False, f"Banned chemical prescription detected: {pattern.pattern}"

    for pattern in BANNED_IRRIGATION_DEPTHS:
        if pattern.search(full_text):
            return False, f"Banned irrigation depth prescription detected: {pattern.pattern}"

    for pattern in BANNED_ABSOLUTE_CLAIMS:
        if pattern.search(full_text):
            return False, f"Banned absolute claim detected: {pattern.pattern}"

    return True, "Valid"


