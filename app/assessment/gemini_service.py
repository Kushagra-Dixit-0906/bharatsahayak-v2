def generate_deterministic_fallback_explanation(
    context: GeminiAssessmentContext,
) -> FarmerAgriculturalResponse:
    """Generates a 100% deterministic pure-Python explanation directly from context.

    Invoked when Gemini API fails, times out, or returns output failing validation.
    Zero external network calls, zero hallucinations, and sets is_fallback=True.
    """
    lang = context.presentation.target_language if context.presentation.target_language in ("en", "hi") else "en"
    cond_key = context.overall_condition if context.overall_condition in FALLBACK_TEMPLATES else "insufficient_evidence"
    tmpl = FALLBACK_TEMPLATES[cond_key][lang]

    # Extract clean observations from structured SupportingEvidenceItem
    observations: list[str] = []
    for pattern in context.identified_patterns:
        for ev in pattern.supporting_evidence:
            obs_str = f"{ev.source}: {ev.metric_name} = {ev.observed_value}"
            if ev.reference_context:
                obs_str += f" ({ev.reference_context})"
            observations.append(obs_str)

    if not observations:
        if context.missing_evidence_sources:
            missing_str = ", ".join(context.missing_evidence_sources)
            observations.append(f"Missing data streams: {missing_str}")
        else:
            observations.append("Baseline environmental monitoring recorded.")

    # Combine limitations
    limitations = list(context.limitations)
    if not limitations and context.maximum_data_lag_days:
        limitations.append(f"Data publication lag: up to {context.maximum_data_lag_days} days.")

    return FarmerAgriculturalResponse(
        language=lang,
        headline=tmpl["headline"],
        summary=tmpl["summary"],
        observations=observations,
        interpretation=tmpl["interpretation"],
        recommended_next_steps=list(tmpl["steps"]),
        limitations=limitations,
        is_fallback=True,
    )


