"""Isolated Gemini Explanation Service for Phase 5C (DEC-024).

This module implements the isolated explanation service that converts a
`GeminiAssessmentContext` into a structured, validated `FarmerAgriculturalResponse`
using Gemini 2.5 Flash, backed by an automated 3-stage validation pipeline and
a 100% deterministic pure-Python fallback generator.

Architectural Invariants:
1. Isolated Service: Not integrated into the production agent or orchestrator flow yet.
2. Controlled Prompt: Must exclusively use build_gemini_prompt(context).
3. Authoritative Assessment: Gemini is an explanation layer; it cannot mutate or
   override Phase 5B deterministic findings.
4. Multi-Layer Validation: Output must pass Pydantic schema validation, structural
   allowlist checks, epistemic invariant checks, and defense-in-depth banned content checks.
5. Deterministic-First Fallback: Any failure (network, parsing, validation) instantly
   routes to a deterministic template generator without raising unhandled errors to the caller.
6. Zero PII / Secret Leakage: API keys and credentials are never placed in prompts or responses.
"""

